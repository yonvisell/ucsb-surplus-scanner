import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { gunzipSync } from "node:zlib";
import path from "node:path";

const dist = path.resolve("dist");
const rawBase = process.env.BASE_PATH || "/ucsb-surplus-scanner/";
if (
  !rawBase.startsWith("/") ||
  !rawBase.endsWith("/") ||
  /[?#\\]/.test(rawBase) ||
  rawBase.split("/").includes("..")
) {
  throw new Error(
    "BASE_PATH must be an absolute path beginning and ending with /",
  );
}
const base = rawBase;

async function listFiles(directory, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const result = [];
  for (const entry of entries) {
    const relative = path.posix.join(prefix, entry.name);
    if (entry.isDirectory())
      result.push(
        ...(await listFiles(path.join(directory, entry.name), relative)),
      );
    else if (entry.isFile()) result.push(relative);
    else throw new Error(`Unsupported entry in dist: ${relative}`);
  }
  return result;
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

const files = (await listFiles(dist))
  .filter((file) => file !== "sw.js" && file !== "offline-manifest.json")
  .sort();
if (!files.includes("index.html"))
  throw new Error(
    "dist/index.html is required before building the service worker",
  );

const assets = await Promise.all(
  files.map(async (file) => {
    const bytes = await readFile(path.join(dist, file));
    return {
      url: base + file.split("/").map(encodeURIComponent).join("/"),
      sha256: sha256(bytes),
      ...(file.endsWith(".gz")
        ? { decodedSha256: sha256(gunzipSync(bytes)) }
        : {}),
      bytes: bytes.byteLength,
    };
  }),
);
const release = sha256(Buffer.from(JSON.stringify({ base, assets })));
const manifest = { schema: 1, base, release, assets };
const manifestBytes = Buffer.from(JSON.stringify(manifest, null, 2) + "\n");
await writeFile(path.join(dist, "offline-manifest.json"), manifestBytes);

// sw.js cannot list its own digest without a cycle. The manifest is cached and
// verified along with every app and vendor asset.
const precache = [
  ...assets,
  {
    url: base + "offline-manifest.json",
    sha256: sha256(manifestBytes),
    bytes: manifestBytes.byteLength,
  },
];

const source = `/* Generated by scripts/build-sw.mjs. Do not edit. */
const RELEASE = ${JSON.stringify(release)};
const SCOPE_PATH = ${JSON.stringify(base)};
const CACHE_PREFIX = 'ucsb-surplus-scanner::' + SCOPE_PATH + '::';
const CACHE_NAME = CACHE_PREFIX + RELEASE;
const ASSETS = ${JSON.stringify(precache)};
const ASSET_PATHS = new Set(ASSETS.map(asset => new URL(asset.url, self.location.origin).pathname));
const INDEX_URL = new URL('index.html', self.registration.scope).href;

async function sha256(response) {
  const digest = await crypto.subtle.digest('SHA-256', await response.arrayBuffer());
  return Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
}

async function verify(cache, checkDigest) {
  const missing = [];
  for (const asset of ASSETS) {
    const response = await cache.match(new URL(asset.url, self.location.origin).href);
    const digest = response && response.ok && checkDigest ? await sha256(response) : undefined;
    if (!response || !response.ok || (checkDigest && digest !== asset.sha256 && digest !== asset.decodedSha256)) {
      missing.push(asset.url);
    }
  }
  return missing;
}

async function repairCache(cache, missing) {
  for (const asset of ASSETS.filter(asset => missing.includes(asset.url))) {
    const url = new URL(asset.url, self.location.origin).href;
    const response = await fetch(new Request(url, { cache: 'reload' }));
    if (!response.ok) throw new Error('Offline file could not be fetched: ' + asset.url);
    const digest = await sha256(response.clone());
    if (digest !== asset.sha256 && digest !== asset.decodedSha256) {
      throw new Error('Offline file verification failed: ' + asset.url);
    }
    // Put only a verified missing entry. A failed repair never removes the
    // already cached app shell and other files.
    await cache.put(url, response);
  }
  const remaining = await verify(cache, false);
  if (remaining.length) throw new Error('Offline cache is incomplete: ' + remaining.join(', '));
}

async function installCache() {
  const existing = (await caches.keys()).includes(CACHE_NAME);
  const cache = await caches.open(CACHE_NAME);
  if (existing) {
    // Worker-only updates can have the same release name as the active worker.
    // Preserve that cache even if an entry needs repair and the network fails.
    const missing = await verify(cache, true);
    if (missing.length) await repairCache(cache, missing);
    return;
  }
  try {
    await cache.addAll(ASSETS.map(asset => new Request(new URL(asset.url, self.location.origin), { cache: 'reload' })));
    const missing = await verify(cache, true);
    if (missing.length) throw new Error('Offline cache verification failed: ' + missing.join(', '));
  } catch (error) {
    await caches.delete(CACHE_NAME);
    throw error;
  }
}

self.addEventListener('install', event => {
  // No skipWaiting here: an existing session chooses when to apply updates.
  event.waitUntil(installCache());
});

self.addEventListener('activate', event => {
  // Retain older app releases so pages opened before an update can still load
  // their older code-split chunks. No cache outside CACHE_PREFIX is touched.
  event.waitUntil(self.clients.claim());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'ACTIVATE_UPDATE') {
    event.waitUntil(self.skipWaiting());
    return;
  }
  if (event.data?.type === 'CHECK_READY' && event.ports[0]) {
    const port = event.ports[0];
    event.waitUntil((async () => {
      try {
        const cache = await caches.open(CACHE_NAME);
        const missing = await verify(cache, false);
        port.postMessage({ type: 'OFFLINE_STATUS', release: RELEASE, ready: missing.length === 0, missing });
      } catch (error) {
        port.postMessage({ type: 'OFFLINE_STATUS', release: RELEASE, ready: false, error: String(error) });
      }
    })());
  }
  if (event.data?.type === 'PREPARE' && event.ports[0]) {
    const port = event.ports[0];
    event.waitUntil((async () => {
      try {
        const cache = await caches.open(CACHE_NAME);
        const missing = await verify(cache, false);
        if (missing.length) await repairCache(cache, missing);
        port.postMessage({ type: 'OFFLINE_STATUS', release: RELEASE, ready: true });
      } catch (error) {
        port.postMessage({ type: 'OFFLINE_STATUS', release: RELEASE, ready: false, error: String(error) });
      }
    })());
  }
});

async function fromOlderAppCache(request) {
  for (const name of (await caches.keys()).filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)) {
    const response = await (await caches.open(name)).match(request);
    if (response) return response;
  }
  return undefined;
}

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(SCOPE_PATH)) return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      return await cache.match(INDEX_URL) || await fetch(request);
    })());
    return;
  }

  const canonical = new URL(url.pathname, self.location.origin).href;
  if (ASSET_PATHS.has(url.pathname)) {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE_NAME);
      const cached = await cache.match(canonical) || await fromOlderAppCache(canonical);
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok) {
        try { await cache.put(canonical, response.clone()); } catch { /* Quota failure is reported by CHECK_READY. */ }
      }
      return response;
    })());
    return;
  }

  // An open page may request a chunk from its preceding release.
  event.respondWith((async () => await fromOlderAppCache(request) || await fetch(request))());
});
`;
await writeFile(path.join(dist, "sw.js"), source);
console.log(
  `Offline release ${release.slice(0, 12)}: ${assets.length} assets, ${assets.reduce((sum, asset) => sum + asset.bytes, 0)} bytes`,
);
